def text_size(s, spacing=1):
    return len(s) * (5 + spacing) - spacing, 7


def draw_text(canvas, x, y, s, color, shadow=None, spacing=1):
    """Draw uppercase text onto an RGBA/RGB uint8 canvas at (x, y)."""
    s = s.upper()
    for i, ch in enumerate(s):
        g = _G.get(ch, _G['?'])
        gx = x + i * (5 + spacing)
        for r, row in enumerate(g):
            for c, px in enumerate(row):
                if px != '#':
                    continue
                for (dx, dy, col) in ((1, 1, shadow), (0, 0, color)):
                    if col is None:
                        continue
                    yy, xx = y + r + dy, gx + c + dx
                    if 0 <= yy < canvas.shape[0] and 0 <= xx < canvas.shape[1]:
                        canvas[yy, xx, :3] = col
                        if canvas.shape[2] == 4:
                            canvas[yy, xx, 3] = 255
